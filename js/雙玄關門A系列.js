let currentColor = '紅鐵砂色';
let currentPattern = 'A1';

const doorImage = document.getElementById('door-image');
const colorNameDisplay = document.getElementById('color-name');
const patternNameDisplay = document.getElementById('pattern-name');

const colorCircles = document.querySelectorAll('.color-circle');
const patternBtns = document.querySelectorAll('.pattern-btn');


function updateVisual() {
    // 更新畫面上的文字
    colorNameDisplay.innerText = currentColor;
    patternNameDisplay.innerText = currentPattern;    
    // 拼湊檔名並換掉圖片
    doorImage.src = `../樣品圖/A系列/${currentColor}_${currentPattern}.png`;
}

// 顏色圈圈點擊
colorCircles.forEach(circle => {
    circle.addEventListener('click', function() {
        // 清除大家的 active
        colorCircles.forEach(c => c.classList.remove('active'));
        // 自己加上 active
        this.classList.add('active');
        // 更新當前顏色並換圖
        currentColor = this.getAttribute('data-color');
        updateVisual();
    });
});

// 門花按鈕點擊
patternBtns.forEach(btn => {
    btn.addEventListener('click', function() {
        patternBtns.forEach(b => b.classList.remove('active'));
        this.classList.add('active');
        currentPattern = this.getAttribute('data-pattern');
        updateVisual();
    });
});